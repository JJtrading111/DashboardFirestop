import assert from 'node:assert/strict';
import { createDemoState, getWorkspace, callEligibility, recordCall, transferUser, inviteUser, reportRows } from './public/model.mjs';

const state = createDemoState();
const now = Date.now();
assert.equal(state.leads.length, 18);
const north = getWorkspace(state, 'c-noord', 'l-03');
const delta = getWorkspace(state, 'c-delta', 'l-03');
assert.notEqual(north, delta);
assert.notEqual(north.notes[0].text, delta.notes[0].text);
const oldDeltaStatus = delta.status;
north.status = 'nieuw';
assert.equal(delta.status, oldDeltaStatus, 'Company status stays separate');
assert.equal(callEligibility(state, 'l-02', 'c-noord', 'u-admin', now).allowed, false);
assert.equal(callEligibility(state, 'l-02', 'c-noord', 'u-admin', now).reason, 'cooldown');
assert.throws(() => recordCall(state, 'l-02', 'c-noord', 'u-admin', now), /wachttijd/);
assert.equal(callEligibility(state, 'l-03', 'c-noord', 'u-admin', now).reason, 'callback');
assert.equal(callEligibility(state, 'l-03', 'c-noord', 'u-thomas', now).allowed, false, 'Colleague callback is no personal exception');
assert.equal(callEligibility(state, 'l-01', 'c-noord', 'u-admin', now).allowed, true, 'Unrelated leads remain callable');
const call = recordCall(state, 'l-03', 'c-noord', 'u-admin', now);
assert.equal(call.userName, 'Mark de Vries');
assert.equal(north.callbacks[0].done, true);
assert.equal(callEligibility(state, 'l-03', 'c-delta', 'u-lisa', now).allowed, false);
const separateFlags = getWorkspace(state, 'c-noord', 'l-15');
assert.equal(separateFlags.commitment, false);
assert.equal(separateFlags.calculation, true);
separateFlags.commitment = true;
assert.equal(separateFlags.calculation, true);
separateFlags.calculation = false;
assert.equal(separateFlags.commitment, true);
const historicalNotes = JSON.stringify(getWorkspace(state, 'c-noord', 'l-04').notes);
const reportsBeforeTransfer = reportRows(state);
transferUser(state, 'u-thomas', 'c-delta');
assert.equal(state.users.find(user => user.id === 'u-thomas').companyId, 'c-delta');
assert.equal(JSON.stringify(getWorkspace(state, 'c-noord', 'l-04').notes), historicalNotes);
assert.equal(getWorkspace(state, 'c-noord', 'l-04').ownerId, 'u-thomas');
assert.deepEqual(reportRows(state), reportsBeforeTransfer, 'Transfer does not move attribution or conversions to another company');
assert.throws(() => transferUser(state, 'u-thomas', 'missing'));
assert.throws(() => inviteUser(state, { name: 'Test', email: 'MARK@NOORDBOUWADVIES.EXAMPLE', companyId: 'c-delta', role: 'verkoper' }), /al een account/);
const invitation = inviteUser(state, { name: 'Nieuwe collega', email: 'nieuw@demo.example', companyId: 'c-noord', role: 'verkoper' });
assert.equal(invitation.demo, true);
assert.throws(() => inviteUser(state, { name: 'Andere collega', email: 'NIEUW@DEMO.EXAMPLE', companyId: 'c-horizon', role: 'verkoper' }), /uitnodiging/);
assert.throws(() => inviteUser(state, { name: 'Ongeldig', email: 'geenadres', companyId: 'c-noord', role: 'verkoper' }));
assert.throws(() => inviteUser(state, { name: 'Ongeldig', email: 'geldig@demo.example', companyId: 'c-noord', role: 'vreemd' }));
const rows = reportRows(state, { companyId: 'c-noord' });
assert(rows.length > 0);
assert(rows.every(row => row.companyId === 'c-noord'));
assert.equal(rows.reduce((total, row) => total + row.total, 0), state.leads.filter(lead => getWorkspace(state, 'c-noord', lead.id).ownerId).length);
assert(rows.some(row => row.sellerId === 'u-thomas'), 'Transferred employee remains in historic company report');
assert(rows.every(row => row.conversion === row.commitments / row.total * 100));
assert(reportRows(state, { companyId: 'c-noord', source: 'hotels' }).every(row => row.source === 'hotels'));
assert.deepEqual(reportRows(state, { from: '2100-01-01' }), []);
const cohortState = createDemoState();
cohortState.leads = cohortState.leads.slice(0, 1);
cohortState.leads[0].createdAt = '2026-06-30T21:30:00.000Z'; // 30 June in Amsterdam.
const cohortWorkspace = getWorkspace(cohortState, 'c-noord', 'l-01');
cohortWorkspace.notes.push({ id: 'today-note', text: 'Recent follow-up', authorId: 'u-admin', authorName: 'Mark de Vries', createdAt: new Date().toISOString() });
cohortWorkspace.calls.push({ id: 'today-call', userId: 'u-admin', userName: 'Mark de Vries', at: new Date().toISOString() });
cohortWorkspace.commitmentAt = new Date().toISOString();
assert.deepEqual(reportRows(cohortState, { companyId: 'c-noord', from: '2026-07-01' }), [], 'A later note, call or conversion never pulls an older lead into the creation cohort');
assert.equal(reportRows(cohortState, { companyId: 'c-noord', from: '2026-06-30', to: '2026-06-30' })[0].total, 1);
cohortState.leads[0].createdAt = '2026-06-30T22:30:00.000Z'; // 1 July in Amsterdam, with summer time.
assert.equal(reportRows(cohortState, { companyId: 'c-noord', from: '2026-07-01', to: '2026-07-01' })[0].total, 1, 'Cohort day uses Amsterdam summer time');
assert.deepEqual(reportRows(cohortState, { companyId: 'c-noord', to: '2026-06-30' }), []);
const restored = JSON.parse(JSON.stringify(state));
assert.equal(getWorkspace(restored, 'c-noord', 'l-04').notes[0].text, JSON.parse(historicalNotes)[0].text);
console.log('Model checks passed: tenant separation, cooldown, callback exception, actor snapshots, independent flags, transfers, invitations, reports and reload-safe data.');
